import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(new URL('../vendor/', import.meta.url), { recursive: true });
const options = { absWorkingDir: root, bundle: true, format: 'iife', platform: 'browser', target: 'es2022', legalComments: 'inline', banner: { js: '/* Generated by npm run build:web from A packages; do not edit. */' } };
await build({ ...options, entryPoints: ['apps/web/src/protocol-browser.ts'], outfile: 'vendor/protocol.js' });
await build({ ...options, entryPoints: ['apps/web/src/showcase-protocol.ts'], outfile: 'docs/shared.js' });
await copyFile(new URL('../docs/shared.js', import.meta.url), new URL('../showcase/shared.js', import.meta.url));
console.log('Browser bundles built from @crosscheck/protocol and @crosscheck/chain/browser.');
